function orderActivity(source, index, priority = 'standard') {
  return {
    id: `lesson2-day3-order-${source.id}`,
    type: 'sentenceOrder',
    lessonId: 'lesson-2',
    day: 3,
    skill: 'writing',
    subskill: 'word-order',
    title: `句子排序 · ${source.id.replace('wb', '')}`,
    instruction: 'Собери предложение из всех частей.',
    pieces: source.pieces.map((text, pieceIndex) => ({
      key: `${source.id}-${pieceIndex}`,
      text,
    })),
    answer: source.answer,
    estimatedSeconds: 120,
    priority,
    errorType: 'word_order',
  }
}

