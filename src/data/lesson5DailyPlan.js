function orderActivity(source, priority = 'standard') {
  return {
    id: `lesson5-day3-order-${source.id}`,
    type: 'sentenceOrder',
    lessonId: 'lesson-5',
    day: 3,
    skill: 'writing',
    subskill: 'word-order',
    title: `句子排序 · ${source.id.replace('wb', '')}`,
    instruction: 'Собери предложение из всех частей.',
    pieces: source.pieces.map((text, pieceIndex) => ({
      key: `${source.id}-${pieceIndex}`,
      text,
    })),
    answer: source.answer,
    answerTokens: source.answerTokens,
    estimatedSeconds: 90,
    priority,
    errorType: 'word_order',
  }
}

