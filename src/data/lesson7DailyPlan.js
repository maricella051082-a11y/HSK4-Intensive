function orderActivity(source, priority = 'standard', lessonDay = 3, prefix = 'order') {
  return {
    id: `lesson7-day${lessonDay}-${prefix}-${source.id}`,
    type: 'sentenceOrder',
    lessonId: 'lesson-7',
    day: lessonDay,
    skill: 'writing',
    subskill: 'word-order',
    title: `句子排序 · ${source.id.replace('wb', '').replace('h41002-', 'HSK ')}`,
    instruction: 'Собери предложение из всех частей.',
    pieces: source.pieces.map((text, pieceIndex) => ({
      key: `${source.id}-${pieceIndex}`,
      text,
    })),
    answer: source.answer,
    answerTokens: source.answerTokens,
    estimatedSeconds: 90,
    priority,
    errorType: 'word_order',
  }
}

